//Example of Wrapper Classes
public class Day_1 {
  public static void main(String[] args){
    //primitive data type
    int num=10;
    //Autoboxing
    Integer obj=num;
    //Unboxing
    int value=obj;

    System.out.println("Primitive:"+num);
    System.out.println("Wrapper Object:"+obj);
    System.out.println("Unboxed Value:"+value);
  }  
}
